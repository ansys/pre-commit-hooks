def repo_review_checks() -> dict:
    families = [
        ProjectMetadata,
        CICDFiles,
        CICD,
        Dependabot,
        PreCommit,
        Documentation,
        README,
        BuildSystem,
        Security,
        Labeler,
        Vale,
        MCP,
    ]
    result = {}
    for family in families:
        for cls in family.__subclasses__():
            result[cls.__name__] = cls()
    return result
